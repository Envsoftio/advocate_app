test('02B pending and failed maps do not reuse prior rows; late check responses cannot replace newer results',async({page,request})=>{
  const {matter}=await fixture(page,request)
  await page.getByRole('button',{name:'Index & bookmarks',exact:true}).click()
  const preview=page.getByRole('region',{name:'Index and page number preview'})
  await expect(preview.locator('tbody tr')).toHaveCount(2)
  let release:()=>void=()=>{}
  const delayed=new Promise<void>(resolve=>{release=resolve})
  let intercepted=0
  await page.route(`**/matters/${matter.id}/bundle-preview`,async route=>{
    if(++intercepted===1){await delayed;await route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Synthetic map calculation failed'})})}
    else await route.continue()
  })
  await page.getByRole('button',{name:'Recalculate map',exact:true}).click()
  await expect(preview).toContainText('Recalculating')
  await expect(preview.locator('tbody tr')).toHaveCount(2)
  await expect(preview.locator('tbody tr').first().locator('td').nth(3)).not.toHaveText(/\d/)
  release()
  await expect(preview).toContainText('Synthetic map calculation failed')
  await expect(preview.locator('tbody tr')).toHaveCount(2)
  await expect(preview.locator('tbody tr').first().locator('td').nth(3)).not.toHaveText(/\d/)
  await preview.getByRole('button',{name:'Retry map',exact:true}).click()
  await expect(preview.locator('tbody tr')).toHaveCount(2)
  await page.getByRole('button',{name:/Preflight checks/}).click()
  let finishOld:()=>void=()=>{}
  const old=new Promise<void>(resolve=>{finishOld=resolve})
  let reads=0
  await page.route(`**/matters/${matter.id}/validate`,async route=>{
    const requestNumber=++reads
    if(requestNumber===1)await old
    await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify([
      {severity:'info',code:'SYNTHETIC_SNAPSHOT',document_id:null,message:requestNumber===1?'Older delayed checks':'Newer completed checks',input_snapshot:requestNumber===1?'old':'new'}
    ])})
  })
  const run=page.getByRole('button',{name:'Run checks',exact:true})
  await run.click()
  await expect(page.locator('.preflight-workspace')).toContainText('Checking the current saved input snapshot')
  await run.click()
  await expect(page.locator('.preflight-workspace')).toContainText('Newer completed checks')
  const oldResponse=page.waitForResponse(async response=>response.url().endsWith(`/matters/${matter.id}/validate`) && (await response.text()).includes('Older delayed checks'))
  finishOld()
  await oldResponse
  await expect.poll(()=>reads).toBe(2)
  await expect(page.locator('.preflight-workspace')).toContainText('Newer completed checks')
  await expect(page.locator('.preflight-workspace')).not.toContainText('Older delayed checks')
})

