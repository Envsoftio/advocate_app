test('02B Save failure and Cancel retain drafts and origin; Save and Discard resume the exact destination',async({page,request})=>{
  const {matter,doc}=await fixture(page,request)
  await openDocumentActions(page)
  await page.getByRole('button',{name:'Document details',exact:true}).click()
  const title=page.getByRole('textbox',{name:'Display title'})
  await page.route(`**/documents/${doc.id}`,route=>route.request().method()==='PATCH'?route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Synthetic save failure'})}):route.continue())
  await title.fill('Retained 02B title')
  const selector=page.getByRole('combobox',{name:'Document version',exact:true})
  await selector.focus()
  await selector.selectOption('original')
  const guard=page.getByRole('alertdialog',{name:'Unsaved work in this tab'})
  await guard.getByRole('button',{name:'Save changes',exact:true}).click()
  await expect(guard).toContainText('Your work and pending destination are retained')
  await expect(title).toHaveValue('Retained 02B title')
  await expect(page.getByRole('dialog',{name:'Review imported original'})).toHaveCount(0)
  await guard.getByRole('button',{name:'Keep editing'}).click()
  await expect(selector).toBeFocused()
  await expect(title).toHaveValue('Retained 02B title')
  await selector.focus()
  await selector.selectOption('original')
  await page.unroute(`**/documents/${doc.id}`)
  await guard.getByRole('button',{name:'Save changes',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'Review imported original'})).toBeVisible()
  const docs=await (await request.get(`${base}/matters/${matter.id}/documents`,{headers})).json()
  expect(docs.find((d:{id:string})=>d.id===doc.id).title).toBe('Retained 02B title')
  await page.getByRole('button',{name:'Close review'}).click()
  await page.getByRole('button',{name:'Close document details',exact:true}).click()
  await closeWorkspaceNavigation(page)
  await page.getByRole('tab',{name:'Edit',exact:true}).click()
  await page.getByRole('button',{name:'Add text',exact:true}).click()
  await page.locator('.pdf-paper').click({position:{x:130,y:200}})
  const draft=page.getByRole('textbox',{name:/Add text on page/})
  await draft.fill('Persisted from navigation')
  await page.route(`**/documents/${doc.id}/annotations`,route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Synthetic PDF save failure'})}))
  await openDocumentBrowser(page)
  await page.locator('.doc-item').filter({hasText:'artifact-beta'}).click()
  await guard.getByRole('button',{name:'Save changes',exact:true}).click()
  await expect(guard).toContainText('PDF tool draft could not be saved')
  await expect(draft).toHaveValue('Persisted from navigation')
  await page.unroute(`**/documents/${doc.id}/annotations`)
  await guard.getByRole('button',{name:'Save changes',exact:true}).click()
  await expect(page.locator('.reader-document strong')).toHaveText('artifact-beta')
  const marks=await (await request.get(`${base}/matters/${matter.id}/annotations`,{headers})).json()
  expect(marks.some((m:{body:string,document_id:string})=>m.body==='Persisted from navigation'&&m.document_id===doc.id)).toBe(true)
  await closeWorkspaceNavigation(page)
  await page.getByRole('tab',{name:'Edit',exact:true}).click()
  await page.getByRole('button',{name:'Add text',exact:true}).click()
  await page.locator('.pdf-paper').click({position:{x:130,y:200}})
  await draft.fill('Discard only this draft')
  await selector.focus()
  await selector.selectOption('original')
  await guard.getByRole('button',{name:'Discard changes',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'Review imported original'})).toContainText('artifact-beta.pdf')
})

