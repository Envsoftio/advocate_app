import { closeWorkspaceNavigation, openDocumentActions, openDocumentBrowser, openWorkspaceNavigation, openWorkspaces } from './navigation'
import {test, expect, type Page, type APIRequestContext} from '@playwright/test'
import {execFileSync} from 'node:child_process'
import {resolve} from 'node:path'
import {existsSync} from 'node:fs'
const base='http://127.0.0.1:8768', headers={Authorization:'Bearer e2e-isolated-token'}
const backendRoot=resolve(import.meta.dirname,'../../backend')
const python=process.env.COURTBUNDLE_TEST_PYTHON || [resolve(backendRoot,'.venv312/bin/python'),resolve(backendRoot,'.venv/bin/python')].find(existsSync) || 'python3'
async function fixture(page:Page,request:APIRequestContext,blank=false){
  page.setDefaultTimeout(15_000)
  const matter=await (await request.post(`${base}/matters`,{headers,data:{name:`02B synthetic ${Date.now()}`,court_profile:blank?'delhi-hc-illustrative':'general-demo'}})).json()
  const bytes=execFileSync(python,['-c',`import pymupdf,sys
pdf=pymupdf.open()
for i in range(3):
 p=pdf.new_page()
 if not (${blank?'True':'False'} and i==1): p.insert_text((40,80),f'Artifact evidence page {i+1}')
sys.stdout.buffer.write(pdf.tobytes())`])
  const docs=[]
  for(const name of ['artifact-alpha','artifact-beta']){
    const upload=await request.post(`${base}/matters/${matter.id}/documents?included=true`,{headers,multipart:{files:{name:`${name}.pdf`,mimeType:'application/pdf',buffer:bytes}}})
    expect(upload.ok()).toBeTruthy();docs.push((await upload.json())[0])
  }
  await page.setViewportSize({width:1440,height:900});await page.goto('/')
  await openWorkspaceNavigation(page)
  await page.locator('.matter-link').filter({hasText:matter.name}).click()
  await openDocumentBrowser(page)
  await page.locator('.doc-item').filter({hasText:'artifact-alpha'}).click()
  await expect(page.locator('.pdf-text-layer')).toContainText('Artifact evidence page 1')
  return {matter,doc:docs[0],second:docs[1]}
}

