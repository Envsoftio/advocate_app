import {test,expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'
import {resolve} from 'node:path'
import {enterLatestMatter,openWorkspaceNavigation,closeWorkspaceNavigation} from './navigation'
const base='http://127.0.0.1:8768',headers={Authorization:'Bearer e2e-isolated-token'}
test('FLOW 06 preserves source, focus panels and frozen output through preparation return',async({page,request},info)=>{
 const matter=await(await request.post(`${base}/matters`,{headers,data:{name:'Focused review synthetic matter',court_profile:'general-demo'}})).json()
 const buffer=await readFile(resolve(import.meta.dirname,'../../samples/01_petition.pdf'))
 const [doc]=await(await request.post(`${base}/matters/${matter.id}/documents?included=true`,{headers,multipart:{files:{name:'Synthetic petition.pdf',mimeType:'application/pdf',buffer}}})).json()
 const job=await(await request.post(`${base}/matters/${matter.id}/build`,{headers})).json()
 await expect.poll(async()=>(await(await request.get(`${base}/jobs/${job.id}`,{headers})).json()).status).toBe('completed')
 const [build]=await(await request.get(`${base}/matters/${matter.id}/exports`,{headers})).json()
 const originalOutput=await(await request.get(`${base}/matters/${matter.id}/exports/${build.id}/inspection/combined.pdf`,{headers})).body()
 expect((await request.patch(`${base}/documents/${doc.id}`,{headers,data:{title:'Reviewed synthetic petition'}})).ok()).toBeTruthy()
 await page.setViewportSize({width:1440,height:900});await page.goto('/');await enterLatestMatter(page)
 await expect(page.locator('.pdf-paper')).toBeVisible()
 const impact=page.getByRole('complementary',{name:'Bundle impact'})
 await expect(impact).toContainText('Previous bundle · Stale')
 await page.getByRole('button',{name:'Next page',exact:true}).click()
 await expect(page.locator('.page-counter input')).toHaveValue('2')
 await page.screenshot({path:info.outputPath('ED33-stale.png'),animations:'disabled'})
 await page.getByRole('button',{name:'Focused reading',exact:true}).click()
 await expect(impact).toBeHidden();await expect(page.locator('.focus-context')).toContainText('Escape restores your panels')
 await expect(page.locator('.page-counter input')).toHaveValue('2')
 await page.screenshot({path:info.outputPath('ED24-focus.png'),animations:'disabled'})
 await page.keyboard.press('Escape');await expect(impact).toBeVisible()
 await expect(page.locator('.page-counter input')).toHaveValue('2')
 await impact.getByRole('button',{name:'View previous output'}).click()
 const artifact=page.getByRole('dialog',{name:'Review generated PDF'})
 await expect(artifact.locator('.pdf-paper')).toBeVisible()
 await expect(artifact.getByRole('complementary',{name:'Artifact information'})).toContainText('Page context')
 await expect(artifact).toContainText('page map is preserved')
 await page.screenshot({path:info.outputPath('ED32-generated.png'),animations:'disabled'})
 await artifact.getByRole('button',{name:'Close review',exact:true}).click()
 for(const width of [1440,1024])for(const theme of ['light','dark'])for(const scale of [100,125]){
  await page.setViewportSize({width,height:width===1440?900:768})
  await openWorkspaceNavigation(page)
  await page.getByRole('combobox',{name:'Theme',exact:true}).selectOption(theme)
  await page.getByRole('combobox',{name:'Interface size'}).selectOption(String(scale))
  await closeWorkspaceNavigation(page)
  await expect(impact.locator('.finding-recheck strong')).toHaveCSS('color','rgb(23, 38, 58)');await expect(impact.locator('.finding-recheck p')).toHaveCSS('color','rgb(23, 38, 58)')
  await impact.getByRole('button',{name:'View previous output'}).scrollIntoViewIfNeeded()
  await expect(impact.getByRole('button',{name:'View previous output'})).toBeInViewport()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy()
  await page.screenshot({path:info.outputPath(`ED33-${width}-${theme}-${scale}.png`),animations:'disabled'})
  if(scale===100){
   await impact.getByRole('button',{name:'View previous output'}).click()
   await expect(artifact.locator('.pdf-paper')).toBeVisible()
   expect((await artifact.locator('.export-review-document').boundingBox())!.width).toBeGreaterThan(400)
   expect((await artifact.locator('.artifact-info-panel').boundingBox())!.x).toBeGreaterThan((await artifact.locator('.export-review-document').boundingBox())!.x)
   await page.screenshot({path:info.outputPath(`ED32-${width}-${theme}.png`),animations:'disabled'})
   await artifact.getByRole('button',{name:'Close review',exact:true}).click()
  }
 }
 await page.locator('.application-status').getByRole('button',{name:'Back to preparation'}).click()
 await expect(page.getByRole('button',{name:'Open editor',exact:true})).toBeVisible()
 await expect(page.locator('.page-counter input')).toHaveValue('2')
 expect((await(await request.get(`${base}/documents/${doc.id}/original`,{headers})).body()).equals(buffer)).toBeTruthy()
 expect((await(await request.get(`${base}/matters/${matter.id}/exports/${build.id}/inspection/combined.pdf`,{headers})).body()).equals(originalOutput)).toBeTruthy()
 expect((await(await request.get(`${base}/matters/${matter.id}/exports`,{headers})).json())[0].stale).toBe(true)
})
