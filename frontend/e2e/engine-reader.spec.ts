async function disconnect(page:Page){
  await page.route(`${base}/**`,route=>route.abort('connectionrefused'))
  await expect(page.locator('.engine-notice').first()).toContainText('Local engine unavailable',{timeout:12000})
}
async function paper(locator:Locator){
  await expect.poll(()=>locator.locator('.pdf-paper').first().evaluate(el=>{
    let {left,top,right,bottom}=el.getBoundingClientRect()
    left=Math.max(0,left);top=Math.max(0,top);right=Math.min(innerWidth,right);bottom=Math.min(innerHeight,bottom)
    for(let p=el.parentElement;p;p=p.parentElement){const r=p.getBoundingClientRect(),s=getComputedStyle(p);if(/auto|scroll|hidden|clip/.test(s.overflowX)){left=Math.max(left,r.left);right=Math.min(right,r.right)}if(/auto|scroll|hidden|clip/.test(s.overflowY)){top=Math.max(top,r.top);bottom=Math.min(bottom,r.bottom)}}
    return right-left>200 && bottom-top>180 && !!document.elementFromPoint((left+right)/2,(top+bottom)/2)?.closest('.reader-page-frame')
  })).toBe(true)
}

test('02C loaded search, reader and unsaved details survive disconnect; retry never replays saves',async({page,request})=>{
  const {doc,matter}=await fixture(page,request)
  await page.getByRole('button',{name:'Search',exact:true}).click()
  const query=page.getByRole('searchbox',{name:'Find text in this PDF'})
  await query.fill('evidence');await expect(page.locator('.pdf-findbar')).toContainText('4 matches')
  await page.getByRole('combobox',{name:'Zoom',exact:true}).selectOption('100')
  const reader=await page.locator('.shared-reader-viewport').elementHandle()
  // Browser internet hints alone must not disable a reachable local engine.
  await page.evaluate(()=>window.dispatchEvent(new Event('offline')))
  await openDocumentActions(page)
  await expect(page.getByRole('button',{name:'Save working copy'})).toBeEnabled()
  await disconnect(page)
  await expect(query).toHaveValue('evidence')
  await query.fill('Recovery');await expect(page.locator('.pdf-findbar')).toContainText('4 matches')
  await openDocumentActions(page)
  await page.getByRole('button',{name:'Document details',exact:true}).click()
  const title=page.getByRole('textbox',{name:'Display title'})
  await title.fill('Retained disconnected draft')
  await expect(page.getByRole('button',{name:'Save document details'})).toBeDisabled()
  await page.unroute(`${base}/**`)
  let writes=0
  page.on('request',r=>{if(r.url().startsWith(base)&&!r.url().includes('/reader-position')&&!['GET','HEAD'].includes(r.method()))writes++})
  await page.getByRole('button',{name:'Retry connection',exact:true}).click()
  await expect(page.locator('.engine-notice')).toHaveCount(0)
  await expect(title).toHaveValue('Retained disconnected draft')
  await expect(page.locator('.metadata-status')).toContainText('use Save')
  await page.waitForTimeout(1800)
  expect(writes).toBe(0)
  expect(await reader!.evaluate(el=>el.isConnected)).toBe(true)
  await expect(page.getByRole('combobox',{name:'Zoom',exact:true})).toHaveValue('100')
  const docs=await (await request.get(`${base}/matters/${matter.id}/documents`,{headers})).json()
  expect(docs.find((d:{id:string})=>d.id===doc.id).title).toBe('recovery')
  await page.getByRole('button',{name:'Save document details'}).click()
  await openDocumentActions(page)
  await expect(page.locator('.metadata-status')).toContainText('Document details saved')
  await title.fill('Autosave resumed after explicit recovery save')
  await expect.poll(async()=>{const docs=await (await request.get(`${base}/matters/${matter.id}/documents`,{headers})).json();return docs.find((d:{id:string})=>d.id===doc.id).title}).toBe('Autosave resumed after explicit recovery save')
})

test('02C stale recovery keeps the PDF draft and old revision until explicit review; no edit replay',async({page,request})=>{
  const {doc}=await fixture(page,request)
  await closeWorkspaceNavigation(page)
  await page.getByRole('tab',{name:'Edit',exact:true}).click()
  await page.getByRole('button',{name:'Add text',exact:true}).click()
  await page.locator('.pdf-paper').click({position:{x:120,y:160}})
  const draft=page.getByRole('textbox',{name:/Add text on page/});await draft.fill('Do not replay this edit')
  await disconnect(page)
  expect((await request.post(`${base}/documents/${doc.id}/pages/rotate`,{headers,data:{page_index:0,degrees:90,expected_revision:doc.revision}})).ok()).toBeTruthy()
  await page.unroute(`${base}/**`)
  const writes:string[]=[];page.on('request',r=>{if(r.url().startsWith(base)&&!r.url().includes('/reader-position')&&!['GET','HEAD'].includes(r.method()))writes.push(r.url())})
  await page.getByRole('button',{name:'Retry connection',exact:true}).click()
  await expect(page.locator('.engine-notice')).toContainText('Saved inputs changed')
  await expect(draft).toHaveValue('Do not replay this edit')
  await expect(page.locator('.application-status')).toContainText('Working revision 1')
  await page.getByRole('button',{name:'Review latest state'}).click()
  const guard=page.getByRole('alertdialog',{name:'Unsaved work in this tab'})
  await expect(guard.getByRole('button',{name:'Save changes',exact:true})).toBeDisabled()
  await guard.getByRole('button',{name:'Keep editing'}).click()
  await expect(page.getByRole('button',{name:'Review latest state'})).toBeFocused()
  await expect(draft).toHaveValue('Do not replay this edit')
  await page.getByRole('button',{name:'Review latest state'}).click()
  await guard.getByRole('button',{name:'Discard changes'}).click()
  await expect(page.locator('.application-status')).toContainText('Working revision 2')
  await expect(page.locator('.engine-notice')).toHaveCount(0)
  expect(writes).toEqual([])
})

