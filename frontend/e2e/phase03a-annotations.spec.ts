import {expect,test} from '@playwright/test'
import {readFile} from 'node:fs/promises'
import {resolve} from 'node:path'
import {closeWorkspaceNavigation,openWorkspaceNavigation} from './navigation'

const base=`http://127.0.0.1:${process.env.MATTERDRAFT_E2E_BACKEND_PORT || 8768}`
const headers={Authorization:'Bearer e2e-isolated-token'}

test('03A highlight and comment Save, retry, reload and source navigation',async({page,request})=>{
  const source=await readFile(resolve(import.meta.dirname,'../../samples/01_petition.pdf'))
  const matter=await (await request.post(`${base}/matters`,{headers,data:{name:'Synthetic 03A review',court_profile:'general-demo'}})).json()
  const [doc]=await (await request.post(`${base}/matters/${matter.id}/documents?included=true`,{headers,multipart:{
    files:{name:'03a-source.pdf',mimeType:'application/pdf',buffer:source},
  }})).json()
  await page.setViewportSize({width:1440,height:900})
  await page.goto('/')
  await expect(page.locator('.application-matter').filter({hasText:'Synthetic 03A review'})).toBeVisible()
  await expect(page.locator('.pdf-text-layer')).toContainText('DRAFT PETITION')
  await page.getByRole('tab',{name:'Annotate'}).click()
  await page.getByRole('button',{name:'Highlight',exact:true}).click()
  await page.getByRole('combobox',{name:'Zoom'}).selectOption('100')
  await page.screenshot({path:test.info().outputPath('ED07-runtime.png')})
  const draw=async(x:number,y:number,w:number,h:number)=>{
    const paper=page.locator('.pdf-paper')
    await paper.scrollIntoViewIfNeeded()
    await expect(page.locator('.pdf-placement-surface')).not.toHaveClass(/is-stale/)
    const box=await paper.boundingBox()
    expect(box).toBeTruthy()
    await page.mouse.move(box!.x+x,box!.y+y)
    await page.mouse.down()
    await page.mouse.move(box!.x+x+w,box!.y+y+h,{steps:7})
    await page.mouse.up()
  }
  await draw(90,125,155,25)
  await page.getByRole('textbox',{name:'Optional highlight note'}).fill('Review this passage')
  await expect(page.locator('.document-save-state')).toContainText('Unsaved changes')
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.pdf-review-highlight')).toHaveCount(1)
  await expect(page.locator('.document-save-state')).toContainText('Saved locally')

  await page.getByRole('button',{name:'Comment',exact:true}).click()
  await draw(270,125,45,26)
  await page.getByRole('textbox',{name:'Comment text'}).fill('Confirm the cited date')
  await page.route(`**/documents/${doc.id}/annotations`,route=>route.request().method()==='POST'
    ? route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({detail:'Synthetic save failure'})})
    : route.continue())
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.document-save-state')).toContainText('Unsaved changes')
  await expect(page.getByRole('textbox',{name:'Comment text'})).toHaveValue('Confirm the cited date')
  await page.unroute(`**/documents/${doc.id}/annotations`)
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.pdf-review-comment')).toHaveCount(1)
  const saved=await (await request.get(`${base}/matters/${matter.id}/annotations`,{headers})).json()
  expect(saved.map((item:{kind:string})=>item.kind).sort()).toEqual(['comment','highlight'])
  for(const item of saved) {
    expect(item.document_id).toBe(doc.id)
    expect(item.page_index).toBe(0)
    expect(item.target_revision).toBe(doc.revision)
    expect(item.output_scope).toBe('private')
    expect(item.created_at).toMatch(/T/)
  }
  await page.reload()
  await expect(page.locator('.pdf-review-highlight')).toHaveCount(1)
  await expect(page.locator('.pdf-review-comment')).toHaveCount(1)
  await page.getByRole('tab',{name:'Annotate'}).click()
  await page.getByRole('button',{name:/Comments \(1\)/}).click()
  await expect(page.getByRole('region',{name:'Private review comments'}).getByText('Confirm the cited date')).toBeVisible()
  await page.screenshot({path:test.info().outputPath('ED09-runtime.png')})
  await page.setViewportSize({width:1024,height:768})
  await openWorkspaceNavigation(page)
  await page.getByRole('combobox',{name:'Theme'}).selectOption('dark')
  await closeWorkspaceNavigation(page)
  await expect(page.locator('html')).toHaveAttribute('data-effective-theme','dark')
  await expect(page.getByRole('region',{name:'Private review comments'}).getByText('Confirm the cited date')).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
  await page.screenshot({path:test.info().outputPath('ED09-compact-dark.png'),animations:'disabled'})
  await page.getByRole('region',{name:'Private review comments'}).getByRole('button',{name:/Source 1/}).click()
  await expect(page.getByRole('textbox',{name:'Comment text'})).toHaveValue('Confirm the cited date')
  await expect(page.locator('.thumbnail-button.selected canvas')).toHaveClass(/is-rendered/)
  await page.screenshot({path:test.info().outputPath('ED08-compact-dark-inspector.png'),animations:'disabled'})
  await expect(page.locator('.document-save-state')).toContainText('Saved locally')
  await expect(page.getByRole('button',{name:'Save',exact:true})).toBeDisabled()
  await page.getByRole('button',{name:'Undo last matter change'}).click()
  await expect(page.locator('.pdf-review-comment')).toHaveCount(0)
  await expect(page.locator('.document-save-state')).toContainText('Saved locally')
  await page.getByRole('button',{name:'Redo last matter change'}).click()
  await expect(page.locator('.pdf-review-comment')).toHaveCount(1)
  const highlightTool=page.getByRole('button',{name:/^Highlight(?: 1)?$/})
  await highlightTool.focus()
  await expect(highlightTool).toBeFocused()
  await highlightTool.press('Enter')
  await expect(highlightTool).toHaveAttribute('aria-pressed','true')
  await draw(90,180,100,22)
  await expect(page.locator('.document-save-state')).toContainText('Unsaved changes')
  await page.keyboard.press('Escape')
  await expect(highlightTool).toHaveAttribute('aria-pressed','false')
  await expect(page.locator('.document-save-state')).toContainText('Saved locally')
  await expect(page.locator('.pdf-review-highlight')).toHaveCount(1)
  const docs=await (await request.get(`${base}/matters/${matter.id}/documents`,{headers})).json()
  expect(docs.find((item:{id:string})=>item.id===doc.id).source_sha256).toBe(doc.source_sha256)
})

test('03A placement stays on rotated source page at 125% zoom',async({page,request})=>{
  const source=await readFile(resolve(import.meta.dirname,'../../samples/01_petition.pdf'))
  const matter=await (await request.post(`${base}/matters`,{headers,data:{name:'Synthetic 03A rotated',court_profile:'general-demo'}})).json()
  const [doc]=await (await request.post(`${base}/matters/${matter.id}/documents?included=true`,{headers,multipart:{
    files:{name:'rotated-03a.pdf',mimeType:'application/pdf',buffer:source},
  }})).json()
  const rotated=await request.post(`${base}/documents/${doc.id}/pages/rotate`,{headers,data:{page_index:1,degrees:90}})
  expect(rotated.ok()).toBe(true)
  const revision=(await rotated.json()).revision as number
  await page.setViewportSize({width:1440,height:900})
  await page.goto('/')
  await expect(page.locator('.application-matter').filter({hasText:'Synthetic 03A rotated'})).toBeVisible()
  await expect(page.locator('.pdf-text-layer')).toContainText('DRAFT PETITION')
  await page.getByRole('tab',{name:'Annotate'}).click()
  await page.getByRole('button',{name:'Next page'}).click()
  await page.getByRole('combobox',{name:'Zoom'}).selectOption('125')
  await page.getByRole('button',{name:'Highlight',exact:true}).click()
  const paper=page.locator('.pdf-paper')
  await paper.scrollIntoViewIfNeeded()
  await expect(page.locator('.pdf-placement-surface')).not.toHaveClass(/is-stale/)
  const box=await paper.boundingBox()
  expect(box).toBeTruthy()
  await page.mouse.move(box!.x+70,box!.y+90)
  await page.mouse.down()
  await page.mouse.move(box!.x+170,box!.y+120,{steps:8})
  await page.mouse.up()
  await page.getByRole('textbox',{name:'Optional highlight note'}).fill('Rotated source page')
  page.once('dialog',dialog=>void dialog.dismiss())
  await page.getByRole('button',{name:'Previous page'}).click()
  await expect(page.getByRole('spinbutton',{name:'Go to page'})).toHaveValue('2')
  await expect(page.locator('.document-save-state')).toContainText('Unsaved changes')
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.document-save-state')).toContainText('Saved locally')
  await expect(page.locator('.pdf-review-highlight')).toHaveCount(1)
  const annotations=await (await request.get(`${base}/matters/${matter.id}/annotations`,{headers})).json()
  expect(annotations).toHaveLength(1)
  expect(annotations[0].document_id).toBe(doc.id)
  expect(annotations[0].page_index).toBe(1)
  expect(annotations[0].target_revision).toBe(revision)
  expect(annotations[0].rect_x).toBeCloseTo(70/box!.width,1)
  expect(annotations[0].rect_y).toBeCloseTo(90/box!.height,1)
  await page.locator('.pdf-review-highlight').click()
  await expect(page.getByRole('button',{name:'Remove selected'})).toBeVisible()
  await page.getByRole('button',{name:'Undo last matter change'}).click()
  await expect(page.locator('.pdf-review-highlight')).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Remove selected'})).toHaveCount(0)
  await page.getByRole('button',{name:'Redo last matter change'}).click()
  await expect(page.locator('.pdf-review-highlight')).toHaveCount(1)
  await page.reload()
  await expect(page.locator('.pdf-review-highlight')).toHaveCount(1)
  await expect(page.getByRole('spinbutton',{name:'Go to page'})).toHaveValue('2')
  const docs=await (await request.get(`${base}/matters/${matter.id}/documents`,{headers})).json()
  expect(docs.find((item:{id:string})=>item.id===doc.id).source_sha256).toBe(doc.source_sha256)
})
