import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { resolve } from 'node:path'

test('matter home leads to overview and focused PDF editing', async ({ page, request }) => {
  const headers = { Authorization: 'Bearer e2e-isolated-token' }
  const base = 'http://127.0.0.1:8768'
  const response = await request.post(`${base}/matters`, { headers, data: {
    name: 'Synthetic workspace design', petitioner: 'Sample Applicant', respondent: 'Sample Respondent',
    case_number: 'DEMO-42', court_profile: 'general-demo',
  } })
  expect(response.ok()).toBeTruthy()
  const matter = await response.json()
  const upload = await request.post(`${base}/matters/${matter.id}/documents`, { headers, multipart: {
    files: { name: '01_petition.pdf', mimeType: 'application/pdf', buffer: await readFile(resolve(import.meta.dirname, '../../samples/01_petition.pdf')) },
  } })
  expect(upload.ok()).toBeTruthy()
  await page.setViewportSize({width:1440,height:1000})
  await page.goto('/')
  await page.getByRole('button', {name:'Matters',exact:true}).click()
  await expect(page.getByRole('heading', {name:'Your matters'})).toBeVisible()
  await page.getByRole('textbox', {name:'Search matters'}).fill('no matching synthetic case')
  await expect(page.getByRole('heading', {name:'No matching matters'})).toBeVisible()
  await page.getByRole('textbox', {name:'Search matters'}).fill('DEMO-42')
  await page.screenshot({path:'test-results/matter-home.png',fullPage:true})
  await page.locator('.matter-home-card').click()
  await expect(page.getByRole('region', {name:'Matter overview'})).toBeVisible()
  await expect(page.locator('.overview-context').first()).toContainText('Sample Applicant')
  await page.screenshot({path:'test-results/matter-overview.png',fullPage:true})
  await page.getByRole('button', {name:'Open documents',exact:true}).click()
  await expect(page.locator('.preview-panel canvas').first()).toBeVisible()
  await expect(page.locator('.document-thumbnail img').first()).toBeVisible()
  await expect.poll(() => page.locator('.document-thumbnail img').first()
    .evaluate((image:HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0)
  await expect(page.locator('.doc-item .document-thumbnail + .doc-info').first()).toContainText('01_petition')
  expect((await page.locator('.docs-panel').boundingBox())!.width).toBeLessThan(240)
  await expect(page.getByRole('group', {name:'Edit PDF',exact:true})).toBeVisible()
  await expect(page.locator('.docs-search').first()).toHaveCSS('height', '36px')
  await expect(page.locator('.zoom-select')).toHaveCSS('height', '36px')
  await page.getByRole('button', {name:'Focus on PDF',exact:true}).click()
  await expect(page.locator('.docs-panel')).toBeHidden()
  await page.getByRole('button', {name:'Show document list',exact:true}).click()
  await expect(page.locator('.docs-panel')).toBeVisible()
  const canvasBefore = await page.locator('.canvas-scroll').boundingBox()
  await page.getByRole('button', {name:'Next page',exact:true}).click()
  await expect(page.locator('.page-counter input')).toHaveValue('2')
  await expect(page.locator('.page-counter')).toContainText('/ 3')
  await page.getByRole('button', {name:'Full screen',exact:true}).click()
  await expect(page.locator('.thumbnail-rail')).toBeVisible()
  await expect(page.locator('.thumbnail-rail .thumbnail-button')).toHaveCount(3)
  await expect(page.locator('.thumbnail-rail canvas[data-page="2"]')).toHaveAttribute('data-rendered', 'true')
  await page.getByRole('button', {name:'Add text'}).click()
  await expect(page.locator('.thumbnail-rail')).toBeVisible()
  await page.getByRole('button', {name:'Select',exact:true}).click()
  await page.locator('.thumbnail-rail').getByRole('button', {name:'Go to page 1'}).click()
  await expect(page.locator('.page-counter input')).toHaveValue('1')
  await page.locator('.thumbnail-rail').getByRole('button', {name:'Go to page 2'}).click()
  await expect(page.locator('.page-counter input')).toHaveValue('2')
  await expect(page.locator('.sidebar')).toBeHidden()
  await expect(page.locator('.open-workspace-tabs')).toBeHidden()
  await expect(page.locator('.workspace-tabs')).toBeHidden()
  await expect(page.locator('.docs-panel')).toBeHidden()
  await expect.poll(async () => (await page.locator('.canvas-scroll').boundingBox())!.height).toBeGreaterThan(canvasBefore!.height)
  await expect.poll(async () => (await page.locator('.preview-panel').boundingBox())!.width).toBeGreaterThan(1430)
  await expect(page.locator('.page-counter input')).toHaveValue('2')
  await expect(page.locator('.page-counter')).toContainText('/ 3')
  await expect(page.getByRole('button', {name:'Document details',exact:true})).toBeInViewport()
  await page.screenshot({path:'test-results/pdf-fullscreen.png',fullPage:true})
  await page.getByRole('button', {name:'Show document list',exact:true}).click()
  await expect(page.locator('.docs-panel')).toBeVisible()
  await page.getByRole('tab', {name:'Pages',exact:true}).click()
  await page.getByRole('button', {name:'Page tools',exact:true}).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', {name:'Page tools'})).toBeHidden()
  await expect(page.getByRole('button', {name:'Exit full screen',exact:true})).toBeVisible()
  await page.getByRole('button', {name:'Exit full screen',exact:true}).click()
  await expect(page.locator('.sidebar')).toBeVisible()
  await expect(page.locator('.docs-panel')).toBeVisible()
  await expect(page.locator('.page-counter input')).toHaveValue('2')
  await expect(page.locator('.page-counter')).toContainText('/ 3')
  await page.getByRole('combobox', {name:'Interface size'}).selectOption('125')
  await page.getByRole('button', {name:'Full screen',exact:true}).click()
  await expect.poll(async () => (await page.locator('.preview-panel').boundingBox())!.width).toBeGreaterThan(1430)
  await expect.poll(async () => (await page.locator('.preview-panel').boundingBox())!.height).toBeLessThanOrEqual(1000)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollHeight <= innerHeight)).toBe(true)
  await page.keyboard.press('Escape')
  await expect(page.locator('.workspace-tabs')).toBeVisible()
  await page.getByRole('combobox', {name:'Interface size'}).selectOption('100')
  await page.screenshot({path:'test-results/pdf-workspace.png',fullPage:true})
  await page.setViewportSize({width:900,height:800})
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', {name:'Full screen',exact:true}).click()
  await expect.poll(async () => (await page.locator('.preview-panel').boundingBox())!.width).toBeGreaterThan(890)
  await expect(page.getByRole('button', {name:'Exit full screen',exact:true})).toBeInViewport()
  await page.keyboard.press('Escape')
  await expect(page.locator('.workspace-tabs')).toBeVisible()
  await page.setViewportSize({width:620,height:800})
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(page.locator('.docs-search').first()).toHaveCSS('height', '36px')
  await page.setViewportSize({width:390,height:800})
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', {name:'Open navigation'}).click()
  await expect(page.locator('.sidebar')).toHaveClass(/mobile-open/)
  await page.locator('.sidebar').getByRole('button', {name:'Close navigation'}).click()
  await expect(page.locator('.sidebar')).not.toHaveClass(/mobile-open/)
})
