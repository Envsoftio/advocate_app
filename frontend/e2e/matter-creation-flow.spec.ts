import { expect, test } from '@playwright/test'

const base = `http://127.0.0.1:${process.env.MATTERDRAFT_E2E_BACKEND_PORT || 8768}`
const headers = { Authorization: 'Bearer e2e-isolated-token' }

test('FLOW 01 empty matters, creation and no-documents overview', async ({ page, request }, info) => {
  await page.setViewportSize({width:1440,height:900})
  await page.goto('/')
  await expect(page.getByText('No matters yet')).toBeVisible()
  const homeHeading=await page.locator('.matter-home .flow-heading h1').boundingBox()
  expect(homeHeading).toMatchObject({x:212})
  const homeViewport=await page.locator('.matter-home').boundingBox()
  const newMatterButton=await page.locator('.matter-home .flow-heading button').boundingBox()
  expect(homeHeading!.y).toBeGreaterThanOrEqual(homeViewport!.y)
  expect(newMatterButton!.y).toBeGreaterThanOrEqual(homeViewport!.y)
  await page.screenshot({path:info.outputPath('01B-empty-matters.png')})
  const chooser=page.waitForEvent('filechooser')
  await page.getByRole('button',{name:'Open existing matter'}).click()
  await chooser
  await page.getByRole('button',{name:'New matter'}).last().click()
  const dialog=page.getByRole('dialog',{name:'Create matter'})
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button',{name:'New matter'}).last().click()
  await expect(dialog).toBeVisible()
  await expect(page.locator('.modal-enter-active')).toHaveCount(0)
  const dialogBox=await dialog.boundingBox()
  expect(dialogBox).toMatchObject({x:370,width:700})
  expect(Math.abs(dialogBox!.y-138)).toBeLessThanOrEqual(1)
  expect(Math.abs(dialogBox!.height-638)).toBeLessThanOrEqual(2)
  await page.screenshot({path:info.outputPath('02A-new-matter.png')})
  await dialog.getByRole('button',{name:'Details…'}).click()
  await expect(dialog).toContainText('configured local app workspace')
  await dialog.getByRole('button',{name:'Details…'}).click()
  await dialog.getByRole('button',{name:'Create matter'}).click()
  await expect(dialog.getByRole('alert')).toContainText('at least two characters')
  await dialog.getByLabel('Matter name').fill('Synthetic creation flow')
  await dialog.getByLabel('Court / forum').fill('Synthetic forum')
  await dialog.getByLabel('Case number').fill('DEMO 01/2026')
  await dialog.getByLabel('Client / party reference').fill('Client-01')
  await dialog.getByLabel('Internal reference').fill('MD-01')
  await dialog.getByLabel('Notes').fill('Synthetic files only')
  await dialog.getByRole('button',{name:'Create matter'}).click()
  await expect(page.getByRole('heading',{name:'Add the source documents'})).toBeVisible()
  await expect(page.locator('.section-enter-active,.section-leave-active,.page-enter-active,.page-leave-active')).toHaveCount(0)
  await expect(page.locator('.new-matter-metrics')).toContainText('0 documents')
  await page.getByRole('button',{name:'Dismiss notification'}).click()
  await expect(page.locator('.toast')).toHaveCount(0)
  await page.screenshot({path:info.outputPath('02B-no-documents.png')})
  await page.setViewportSize({width:1024,height:768})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(page.getByRole('button',{name:'Import documents',exact:true})).toBeInViewport()
  const matters=await (await request.get(`${base}/matters`,{headers})).json()
  expect(matters[0]).toMatchObject({name:'Synthetic creation flow',court_forum:'Synthetic forum',case_number:'DEMO 01/2026',client_reference:'Client-01',internal_reference:'MD-01',notes:'Synthetic files only'})
  await page.getByRole('button',{name:'Matter details'}).click()
  await expect(page.getByRole('dialog',{name:'Matter details'})).toContainText('Synthetic files only')
  await page.getByRole('button',{name:'Close matter details'}).click()
  await page.getByRole('button',{name:'Import documents',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Import documents'})).toBeVisible()
})

test('new matter dialog scrolls inside a short or compact app window', async ({page}, info) => {
  await page.setViewportSize({width:1400,height:430})
  await page.goto('/')
  await page.getByRole('button',{name:'New matter'}).last().click()
  const dialog=page.getByRole('dialog',{name:'Create matter'})
  await expect(dialog).toBeVisible()
  await expect(page.locator('.modal-enter-active,.modal-leave-active')).toHaveCount(0)
  for(const width of [1400,560]) {
    await page.setViewportSize({width,height:430})
    await dialog.evaluate(el => {el.scrollTop=0})
    await page.waitForTimeout(150)
    await page.screenshot({path:info.outputPath(`02A-short-${width}-top.png`)})
    const box=await dialog.boundingBox()
    expect(box).not.toBeNull()
    expect(box!.y).toBeGreaterThanOrEqual(0)
    expect(box!.y+box!.height).toBeLessThanOrEqual(430)
    const scroll=await dialog.evaluate(el=>({client:el.clientHeight,total:el.scrollHeight}))
    expect(scroll.total).toBeGreaterThan(scroll.client)
    await page.mouse.move(box!.x+box!.width/2,box!.y+box!.height/2)
    await page.mouse.wheel(0,1000)
    await expect.poll(()=>dialog.evaluate(el=>el.scrollTop)).toBeGreaterThan(0)
    await expect(dialog.getByRole('button',{name:'Create matter'})).toBeInViewport()
    const settings=await dialog.getByText('Preparation settings').boundingBox()
    const footer=await dialog.locator('.new-matter-actions').boundingBox()
    expect(footer!.y-(settings!.y+settings!.height)).toBeGreaterThanOrEqual(8)
    await page.screenshot({path:info.outputPath(`02A-short-${width}-bottom.png`)})
  }
  await dialog.getByText('Preparation settings').click()
  await dialog.getByRole('button',{name:'Create matter'}).scrollIntoViewIfNeeded()
  await expect(dialog.getByRole('button',{name:'Create matter'})).toBeInViewport()
})
