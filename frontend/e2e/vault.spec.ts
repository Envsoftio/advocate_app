import { expect, test } from '@playwright/test'

test.skip(process.env.MATTERDRAFT_E2E_REQUIRE_VAULT !== '1', 'Run with MATTERDRAFT_E2E_REQUIRE_VAULT=1')

test('sets up and unlocks the protected synthetic workspace', async ({ page, request }) => {
  await page.addInitScript(() => localStorage.setItem('courtbundle.appearance.v1', JSON.stringify({theme:'dark',scale:100})))
  await page.route('http://127.0.0.1:8768/health', async route => {
    await new Promise(resolve => setTimeout(resolve, 700))
    await route.continue()
  }, {times:1})
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Starting local engine' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-effective-theme', 'dark')
  await expect(page.locator('.vault-screen')).toHaveCSS('background-color', 'rgb(12, 20, 33)')
  await expect(page.locator('.vault-card')).toHaveCSS('background-color', 'rgb(23, 35, 52)')
  await expect(page.locator('.vault-heading')).toHaveCSS('user-select', 'none')
  await expect(page.getByRole('heading', { name: 'Protect local matters' })).toBeVisible()
  await expect(page.getByLabel('New password', { exact: true })).toHaveCSS('background-color', 'rgb(16, 27, 42)')
  const locked = await request.get('http://127.0.0.1:8768/matters', {
    headers: { Authorization: 'Bearer e2e-isolated-token' },
  })
  expect(locked.status()).toBe(423)
  await page.getByLabel('New password', { exact: true }).fill('ab1234')
  await page.getByLabel('Confirm password', { exact: true }).fill('ab1234')
  await expect(page.getByLabel('New password', { exact: true })).toHaveAttribute('type', 'password')
  await page.getByRole('button', { name: 'Show New password' }).click()
  await expect(page.getByLabel('New password', { exact: true })).toHaveAttribute('type', 'text')
  await expect(page.getByLabel('New password', { exact: true })).toHaveValue('ab1234')
  await expect(page.getByLabel('Confirm password', { exact: true })).toHaveAttribute('type', 'password')
  await page.getByRole('button', { name: 'Hide New password' }).click()
  await expect(page.getByLabel('New password', { exact: true })).toHaveAttribute('type', 'password')
  await page.getByRole('button', { name: 'Show Confirm password' }).click()
  await expect(page.getByLabel('Confirm password', { exact: true })).toHaveAttribute('type', 'text')
  await page.getByRole('button', { name: 'Protect and open' }).click()
  await expect(page.getByRole('heading', { name: 'Save your recovery key' })).toBeVisible()
  await expect(page.locator('.vault-recovery-key')).toHaveCSS('background-color', 'rgb(14, 25, 40)')
  await expect(page.locator('.vault-recovery-warning')).toHaveCSS('color', 'rgb(255, 216, 152)')
  await expect(page.locator('.vault-recovery code')).toHaveCSS('user-select', 'all')
  const recovery = await page.locator('.vault-recovery code').textContent()
  expect(recovery).toMatch(/^[0-9a-f]{64}$/)
  await page.getByRole('button', { name: 'I saved the recovery key' }).click()
  await expect(page.getByRole('button', { name: 'New matter' })).toBeVisible()
  await page.getByRole('button', { name: 'Change vault password' }).click()
  await page.getByLabel('New password', { exact: true }).fill('xy9876')
  await page.getByLabel('Confirm password', { exact: true }).fill('xy9876')
  await expect(page.getByLabel('New password', { exact: true })).toHaveAttribute('type', 'password')
  await page.getByRole('button', { name: 'Change password' }).click()
  await expect(page.getByRole('heading', { name: 'Save your recovery key' })).toBeVisible()
  await page.getByRole('button', { name: 'I saved the recovery key' }).click()
  const status = await request.get('http://127.0.0.1:8768/vault/status', {
    headers: { Authorization: 'Bearer e2e-isolated-token' },
  })
  expect((await status.json()).state).toBe('unlocked')
})
