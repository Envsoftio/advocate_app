//! Printable ASCII glyph rectangles in thousandths of an em for the Latin Base14 faces.
//! Measurements from the reference renderer, used only for PDF text collision geometry.

#[derive(Clone, Copy)]
pub(super) enum Font {
    Helvetica,
    HelveticaBold,
    HelveticaOblique,
    HelveticaBoldOblique,
    TimesRoman,
    TimesBold,
    TimesItalic,
    TimesBoldItalic,
    Courier,
    CourierBold,
    CourierOblique,
    CourierBoldOblique,
}

impl Font {
    pub fn named(name: &str) -> Option<Self> {
        Some(match name {
            "Helvetica" => Self::Helvetica,
            "Helvetica-Bold" => Self::HelveticaBold,
            "Helvetica-Oblique" => Self::HelveticaOblique,
            "Helvetica-BoldOblique" => Self::HelveticaBoldOblique,
            "Times-Roman" => Self::TimesRoman,
            "Times-Bold" => Self::TimesBold,
            "Times-Italic" => Self::TimesItalic,
            "Times-BoldItalic" => Self::TimesBoldItalic,
            "Courier" => Self::Courier,
            "Courier-Bold" => Self::CourierBold,
            "Courier-Oblique" => Self::CourierOblique,
            "Courier-BoldOblique" => Self::CourierBoldOblique,
            _ => return None,
        })
    }

    pub fn glyph(self, ch: char) -> Option<[i16; 4]> {
        let index = usize::try_from(u32::from(ch).checked_sub(32)?).ok()?;
        let bounds = match self {
            Self::Helvetica => &super::helvetica_bounds::ASCII_BOUNDS,
            Self::HelveticaBold => &HEBO,
            Self::HelveticaOblique => &HEIT,
            Self::HelveticaBoldOblique => &HEBI,
            Self::TimesRoman => &TIRO,
            Self::TimesBold => &TIBO,
            Self::TimesItalic => &TIIT,
            Self::TimesBoldItalic => &TIBI,
            Self::Courier => &COUR,
            Self::CourierBold => &COBO,
            Self::CourierOblique => &COIT,
            Self::CourierBoldOblique => &COBI,
        };
        bounds.get(index).copied()
    }
}

